import { writeFileSync } from 'node:fs';
import { SECURITY_HEADERS, ASSET_CACHE } from '../config/security-headers.mjs';

export const headersFile = () =>
  `# Generated by scripts/gen-headers.mjs. Edit config/security-headers.mjs instead.\n/*\n${Object.entries(SECURITY_HEADERS).map(([k, v]) => `  ${k}: ${v}`).join('\n')}\n\n/assets/*\n  Cache-Control: ${ASSET_CACHE}\n`;

export const vercelFile = () =>
  `${JSON.stringify({
    headers: [
      { source: '/(.*)', headers: Object.entries(SECURITY_HEADERS).map(([key, value]) => ({ key, value })) },
      { source: '/assets/(.*)', headers: [{ key: 'Cache-Control', value: ASSET_CACHE }] },
    ],
  }, null, 2)}\n`;

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('../public/_headers', import.meta.url), headersFile());
  writeFileSync(new URL('../vercel.json', import.meta.url), vercelFile());
  console.log('Wrote public/_headers and vercel.json');
}
